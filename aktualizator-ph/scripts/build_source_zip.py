"""Create a canonical source archive from validated regular files only.

The JSON recipe is generated by the updater, but treat every path and byte
as untrusted. A member is accepted only under an explicitly trusted cache
root and only if its SHA-256 agrees with the pre-recorded source evidence.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
import zipfile


def safe_name(name):
    return (isinstance(name, str) and bool(name) and '\\' not in name
            and '\\0' not in name and not Path(name).is_absolute()
            and all(part not in {'.', '..', ''} for part in name.split('/')))


def allowed_roots(recipe_path):
    roots = [recipe_path.parent, Path.cwd() / '.source-cache', Path.cwd() / '.public-state']
    for env in ('LAW_SOURCE_CACHE_DIR', 'LAW_XML_SOURCE_ROOT', 'RUNNER_TEMP'):
        if os.environ.get(env):
            roots.append(Path(os.environ[env]))
    return [root.resolve() for root in roots]


def checked_source(raw, roots):
    if not isinstance(raw, str):
        raise ValueError('Invalid source path')
    source = Path(raw)
    if not source.is_absolute() or '..' in source.parts or source.absolute() != source.resolve():
        raise ValueError('Source traversal or symlinked parent')
    if not any(source.is_relative_to(root) and source != root for root in roots):
        raise ValueError('Source outside trusted cache root')
    if not stat.S_ISREG(source.lstat().st_mode):
        raise ValueError('Source must be a regular file')
    return source


def copy_verified(archive, row, roots):
    name = row['name']
    if not safe_name(name):
        raise ValueError('Invalid source archive member')
    source = checked_source(row['path'], roots)
    size = row.get('size')
    expected = row.get('sha256')
    if (type(size) is not int or size < 0 or
            not isinstance(expected, str) or not re.fullmatch(r'[a-f0-9]{64}', expected)):
        raise ValueError('Source size and SHA-256 are required')
    flags = os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0)
    descriptor = os.open(source, flags)
    try:
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode) or before.st_size != size:
            raise ValueError('Source type or size changed')
        entry = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
        entry.compress_type = zipfile.ZIP_DEFLATED
        digest = hashlib.sha256()
        total = 0
        with os.fdopen(os.dup(descriptor), 'rb') as incoming:
            with archive.open(entry, 'w', force_zip64=size >= 2**31) as outgoing:
                for chunk in iter(lambda: incoming.read(1024 * 1024), b''):
                    outgoing.write(chunk)
                    digest.update(chunk)
                    total += len(chunk)
        after = os.fstat(descriptor)
        current = source.lstat()
        if (total != size or digest.hexdigest() != expected or
                (before.st_dev, before.st_ino, before.st_mtime_ns, before.st_ctime_ns) !=
                (after.st_dev, after.st_ino, after.st_mtime_ns, after.st_ctime_ns) or
                (before.st_dev, before.st_ino) != (current.st_dev, current.st_ino)):
            raise ValueError('Source changed while archiving')
    finally:
        os.close(descriptor)


def build(recipe, recipe_path):
    roots = allowed_roots(recipe_path)
    target = Path(recipe['target'])
    if target != recipe_path.parent / 'source.zip' or target.is_symlink():
        raise ValueError('Archive must be created in recipe directory')
    names = set()
    rows = recipe['files'] + [dict(name='manifest.json', path=recipe['catalog'],
                                    size=recipe['catalogSize'], sha256=recipe['catalogSha256'])]
    # Reserve output exclusively; no existing file or symlink may be replaced.
    with target.open('xb') as output:
        with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED,
                             compresslevel=6, allowZip64=True) as archive:
            for row in rows:
                if row['name'] in names:
                    raise ValueError('Duplicate source archive member')
                names.add(row['name'])
                copy_verified(archive, row, roots)


if __name__ == '__main__':
    try:
        recipe_path = Path(sys.argv[1]).resolve(strict=True)
        if recipe_path.is_symlink() or not recipe_path.is_file():
            raise ValueError('Invalid archive recipe')
        build(json.loads(recipe_path.read_bytes()), recipe_path)
    except Exception:
        print('Original-source archive rejected.', file=sys.stderr)
        raise SystemExit(1)
